def gc_percent(guide):
    gc = guide.count("G") + guide.count("C")
    return gc / len(guide) * 100

def reverse_complement(s):
    pairs = {"A": "T", "T": "A", "G": "C", "C": "G"}
    flipped = ""
    for letter in s:
        flipped = flipped + pairs[letter]
    return flipped[::-1]

def find_guides(sequence, strand):
    found = []
    for i in range(len(sequence) - 2):
        if sequence[i+1:i+3] == "GG":
            if i >= 20:
                guide = sequence[i-20:i]
                pam = sequence[i:i+3]
                gc = gc_percent(guide)
                if 40 <= gc <= 60:
                    found.append((abs(gc - 50), strand, guide, pam, gc))
    return found

forward = find_guides(seq, "+")
reverse = find_guides(reverse_complement(seq), "-")

results = forward + reverse
results.sort()

for item in results[:10]:
    print(item[1], item[2], item[3], item[4])

print("Gene length:", len(seq))
print("Forward guides:", len(forward))
print("Reverse guides:", len(reverse))
print("Total guides:", len(results))
